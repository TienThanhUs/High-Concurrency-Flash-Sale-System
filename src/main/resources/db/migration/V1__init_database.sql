-- V1__init_schema.sql (PostgreSQL Version)

CREATE TABLE users (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       username VARCHAR(50) NOT NULL UNIQUE,
                       password_hash VARCHAR(255) NOT NULL,
                       email VARCHAR(100) NOT NULL UNIQUE,
                       role VARCHAR(20) DEFAULT 'USER',
                       created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE products (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          name VARCHAR(255) NOT NULL,
                          description TEXT,
                          original_price DECIMAL(10, 2) NOT NULL,
                          general_stock INT NOT NULL DEFAULT 0,
                          created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE campaigns (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           name VARCHAR(100) NOT NULL,
                           start_time TIMESTAMP NOT NULL,
                           end_time TIMESTAMP NOT NULL,
                           status VARCHAR(20) DEFAULT 'UPCOMING',
                           created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE campaign_items (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                campaign_id BIGINT NOT NULL,
                                product_id BIGINT NOT NULL,
                                flash_sale_price DECIMAL(10, 2) NOT NULL,
                                total_quantity INT NOT NULL,
                                available_quantity INT NOT NULL,
                                version INT DEFAULT 0, -- Dùng cho Optimistic Locking của JPA
                                FOREIGN KEY (campaign_id) REFERENCES campaigns(id) ON DELETE CASCADE,
                                FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
);

-- 5. Bảng orders (Đơn đặt hàng)
CREATE TABLE orders (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        user_id BIGINT NOT NULL,
                        campaign_item_id BIGINT NOT NULL,
                        status VARCHAR(20) DEFAULT 'PENDING',
                        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                        FOREIGN KEY (user_id) REFERENCES users(id),
                        FOREIGN KEY (campaign_item_id) REFERENCES campaign_items(id)
);

-- ========================================================
-- TẠO INDEX (Chỉ mục)
-- ========================================================
CREATE INDEX idx_campaign_items_campaign_id ON campaign_items(campaign_id);
CREATE INDEX idx_orders_user_id ON orders(user_id);
CREATE INDEX idx_orders_campaign_item_id ON orders(campaign_item_id);
CREATE UNIQUE INDEX idx_unique_order_user_campaign_item ON orders(user_id, campaign_item_id);